import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
const folder = '../docs/m3/screenshots'
test.setTimeout(180_000)
test('M3 artwork, processing, presets, text, responsive layout and both themes', async ({ page }) => {
  mkdirSync(folder, { recursive: true })
  const audits: any[] = []
  await page.setViewportSize({ width: 1440, height: 960 }); await page.emulateMedia({ colorScheme: 'light' }); await page.goto('/')
  await expect(page.getByRole('button', { name: 'Choose Image', exact: true })).toBeEnabled()
  await page.screenshot({ path: `${folder}/01-start-light.png`, fullPage: true })
  await page.setInputFiles('[aria-label="Choose image file"]', { name: 'Atelier mark.svg', mimeType: 'image/svg+xml', buffer: readFileSync(new URL('./corpus/simple-logo.svg', import.meta.url)) })
  await page.getByRole('button', { name: 'Make Stencil', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Export STL', exact: true })).toHaveAttribute('aria-disabled', 'false', { timeout: 90000 })
  await expect(page.locator('.mesh-preview')).toHaveAttribute('data-ready', 'true')
  await page.screenshot({ path: `${folder}/02-stencil-light.png`, fullPage: true })
  await page.getByRole('button', { name: 'Customize artwork', exact: true }).click()
  await page.locator('.artwork-operation').filter({ hasText: 'Crop & rotate' }).locator('summary').first().click()
  await page.screenshot({ path: `${folder}/04-artwork-tools-light.png`, fullPage: true })
  await page.getByRole('navigation', { name: 'Settings categories' }).getByRole('button', { name: 'Processing steps', exact: true }).click()
  await page.locator('.step-select').filter({ hasText: 'Trace outlines' }).click()
  await page.screenshot({ path: `${folder}/05-processing-light.png`, fullPage: true })
  await page.getByRole('navigation', { name: 'Settings categories' }).getByRole('button', { name: 'Presets and history', exact: true }).click()
  await page.getByRole('combobox', { name: 'Preset operation', exact: true }).selectOption('outlines')
  await page.getByRole('textbox', { name: 'Preset name', exact: true }).fill('Clean outline')
  await page.getByRole('button', { name: 'Save operation preset', exact: true }).click()
  await page.screenshot({ path: `${folder}/06-presets-light.png`, fullPage: true })
  await page.getByRole('searchbox').fill('smooth edges'); await page.locator('.setting-reference summary').first().click()
  await page.screenshot({ path: `${folder}/07-all-settings-light.png`, fullPage: true })
  await page.getByRole('button', { name: 'Close settings', exact: true }).click()
  await page.getByRole('combobox', { name: 'Inspect artwork stage', exact: true }).selectOption('outlines/shapes')
  await expect(page.locator('.stage-image')).toHaveAttribute('data-ready', 'true')
  await page.screenshot({ path: `${folder}/08-outlines-light.png`, fullPage: true })
  await page.getByRole('button', { name: 'Switch to dark mode', exact: true }).click()
  await page.screenshot({ path: `${folder}/09-outlines-dark.png`, fullPage: true })
  await page.getByRole('button', { name: 'Processing Steps', exact: true }).click()
  await page.locator('.step-select').filter({ hasText: 'Remove small shapes' }).click()
  await page.screenshot({ path: `${folder}/10-processing-dark.png`, fullPage: true })
  for (const width of [1440, 800, 390]) {
    await page.setViewportSize({ width, height: 960 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(await page.locator('.settings-dialog').evaluate(e => e.scrollWidth <= e.clientWidth)).toBe(true)
    const axe = await new AxeBuilder({ page }).include('.settings-dialog').withTags(['wcag2a', 'wcag2aa']).analyze()
    const severe = axe.violations.filter(v => ['critical', 'serious'].includes(v.impact ?? ''))
    expect(severe).toEqual([]); audits.push({ width, serious_or_critical: severe.length })
  }
  await page.screenshot({ path: `${folder}/11-processing-mobile-dark.png`, fullPage: true })
  await page.getByRole('button', { name: 'Close settings', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.getByRole('button', { name: 'New Project', exact: true }).click()
  await page.getByRole('button', { name: 'Create from Text', exact: true }).click()
  await page.getByRole('textbox', { name: 'Text · text-artwork', exact: true }).fill('AOBR\nSTENCIL')
  await page.getByRole('spinbutton', { name: 'Letter height (px) · text-artwork', exact: true }).fill('120')
  await page.screenshot({ path: `${folder}/12-text-editor-dark.png`, fullPage: true })
  await page.getByRole('button', { name: 'Close settings', exact: true }).click()
  await page.getByRole('button', { name: 'Make Stencil', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Export STL', exact: true })).toHaveAttribute('aria-disabled', 'false', { timeout: 90000 })
  await page.getByRole('tab', { name: '3D', exact: true }).click()
  await expect(page.locator('.mesh-preview')).toHaveAttribute('data-ready', 'true')
  await page.screenshot({ path: `${folder}/13-text-stencil-dark.png`, fullPage: true })
  await page.getByRole('button', { name: 'Switch to light mode', exact: true }).click()
  await page.screenshot({ path: `${folder}/14-text-stencil-light.png`, fullPage: true })
  writeFileSync('../docs/m3/responsive-accessibility.json', JSON.stringify({ processing_dialog: audits, themes: ['light', 'dark'] }, null, 2))
})
